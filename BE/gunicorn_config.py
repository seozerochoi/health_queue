# ============================================================
# Gunicorn Configuration for Health Queue Backend
# AWS EC2 (2 CPU, 2GB RAM) + nginx 최적화
# ============================================================

# ============================================================
# 1. 서버 바인드 설정
# ============================================================
# ⚡ CRITICAL: nginx와 통신하는 핵심 설정
# TCP 소켓: 원격 서버에서도 접근 가능 (이 경우는 localhost만 접근)
# Unix 소켓: 로컬 머신에서만 접근, 성능 우수 (권장)
bind = '127.0.0.1:8000'
# bind = 'unix:/tmp/gunicorn.sock'  # 성능 최적화 버전

# ============================================================
# 2. Worker 설정 (동시성 처리)
# ============================================================
# AWS 2 CPU 환경에 최적화
# 공식 권장: workers = (2 × CPU_cores) + 1 = (2 × 2) + 1 = 5
workers = 5  # 4개 worker (성능 우선)

# Worker 클래스: sync (기본값, 가장 빠름)
# SSE가 필요하면 gevent 고려, 일반 API는 sync가 최적
# worker_class = 'sync'  # 기본값이므로 주석 처리

# gthread는 SSE용으로 필요할 때만 활성화
# worker_class = 'gthread'
# threads = 4

worker_class = 'gevent'  # SSE 지원

# ============================================================
# 3. 타임아웃 설정
# ============================================================
# SSE는 장시간 연결을 유지하므로 충분히 긴 시간 설정 필수
# ⚠️ nginx timeout과 일치해야 함 (기본값 300s)
timeout = 300  # 5분 (SSE + 느린 쿼리 포용)

# Graceful timeout: worker 종료 시 대기 시간
# systemd에서 TimeoutStopSec과 맞춰서 설정
graceful_timeout = 30

# temp 파일/소켓을 메모리 파일시스템(/dev/shm)에 두어 I/O 대기 감소
# worker_tmp_dir = '/dev/shm'

# PID 파일 (빠른 reload를 위해)
# pidfile = '/tmp/gunicorn.pid'

# ============================================================
# 4. 로그 설정
# ============================================================
# ⚡ 성능 우선: 로그 최소화
# 프로덕션에서는 info 레벨만 사용 (debug는 개발 시에만)
loglevel = 'info'

# Access log: 요청/응답 시각, 메서드, 경로, 상태 코드, 처리 시간
# %(t)s: 요청 시각 (로컬 타임존 - 한국 시간)
# %(m)s: 메서드 (GET, POST 등)
# %(U)s: URL 경로
# %(s)s: 상태 코드
# %(L)s: 요청 처리 시간 (초)
# 포맷: [요청시각] 메서드 경로 → 상태코드 (처리시간)
access_log_format = '%(t)s %(m)s %(U)s → %(s)s (%(L)ss)'
accesslog = '-'   # stdout으로 출력

# Error log
errorlog = '-'    # stderr로 출력 (systemd journal 수집)

# 로그 캡처 설정: 성능을 위해 최소화
capture_output = False

# ============================================================
# 5. 연결 설정
# ============================================================
# Keep-alive 연결 타임아웃
keepalive = 65

# 요청 라인/필드 제한
limit_request_line = 4096
limit_request_fields = 100

# ============================================================
# 6. 메모리/성능 최적화
# ============================================================
# Preload app: 각 worker가 독립적으로 앱 로드
# - True: 메모리 절약, 느린 재시작
# - False: 메모리 증가, 빠른 재시작 (현재 설정)
preload_app = False

# Worker 재시작 정책 (메모리 누수 방지)
# worker 당 처리 요청 수 초과 시 재시작
max_requests = 1000  # 1000개 요청 후 재시작
max_requests_jitter = 50  # ±50개 범위에서 무작위

# ============================================================
# 7. 요청 처리 (SSE 호환)
# ============================================================
# 청크 인코딩 지원 (SSE 필수)
chunked_transfer_encoding = True

# 버퍼링 비활성화 (SSE 필수)
# gunicorn이 응답을 버퍼링하면 SSE가 제때 도착하지 않음
# (하지만 gunicorn에는 직접 설정이 없고, nginx에서 처리)

